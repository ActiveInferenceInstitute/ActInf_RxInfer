"""Measure the gate arms and render the recorded numbers.

``./run.sh measure`` is this script. It runs every arm of ``./run.sh`` once,
times each arm's whole process, and writes two files:

* ``docs/_generated/gate-receipt.json`` — the measurement record;
* ``docs/_generated/gate.md`` — the rendered table, committed next to it.

``--check`` re-renders the table from the committed receipt and compares it
with the committed Markdown, so a hand-edited number is a finding rather than a
silently stale document. The ``docs`` arm runs it after link checking.

The measurement covers the arms that were run; the ``docs`` arm is measured
last, after the receipt and table exist, so its own check validates the files
this run just wrote.

Usage: ``python3 scripts/gate_report.py [--check] [--arms lint,fast,...] [--json]``

Exit codes: ``0`` measured and written (or ``--check`` matched), ``1`` an arm
failed or the committed table does not match the receipt.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECEIPT = ROOT / "docs" / "_generated" / "gate-receipt.json"
TABLE = ROOT / "docs" / "_generated" / "gate.md"
SCHEMA = "actinf-rxinfer-gate/v1"
ALL_ARMS = ("lint", "fast", "full", "gnn")
LAST_ARM = "docs"

TEST_SUMMARY = re.compile(r"^ActInf_RxInfer \|(?P<rest>.*)$", re.MULTILINE)
GNN_SUMMARY = re.compile(r"parsed by gnn (\S+)")
GNN_PIN_COMMIT = re.compile(r'"commit": "([0-9a-f]{40})"|git archive of ([0-9a-f]{40})')


def run_command(argv: list[str]) -> str | None:
    try:
        completed = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True)
    except FileNotFoundError:
        return None
    if completed.returncode != 0:
        return None
    return completed.stdout.strip()


def test_counts(output: str) -> dict[str, int] | None:
    rows = TEST_SUMMARY.findall(output)
    if not rows:
        return None
    columns = re.sub(r"[\d.]+s$", "", rows[-1].strip())
    numbers = [int(value) for value in re.findall(r"\d+", columns)]
    if not numbers:
        return None
    total = numbers[-1]
    passed = numbers[0]
    deferred = numbers[1] if len(numbers) == 3 else 0
    return {"passed": passed, "deferred": deferred, "total": total}


def gnn_facts(output: str) -> dict[str, str]:
    facts: dict[str, str] = {}
    version = GNN_SUMMARY.search(output)
    if version:
        facts["version"] = version.group(1)
    commit = GNN_PIN_COMMIT.search(output)
    if commit:
        facts["commit"] = commit.group(1) or commit.group(2)
    return facts


def measure_arm(name: str) -> dict[str, object]:
    started = time.monotonic()
    completed = subprocess.run(
        [str(ROOT / "run.sh"), name], cwd=ROOT, capture_output=True, text=True
    )
    seconds = time.monotonic() - started
    sys.stdout.write(completed.stdout)
    sys.stderr.write(completed.stderr)
    output = completed.stdout + completed.stderr
    record: dict[str, object] = {
        "arm": name,
        "command": f"./run.sh {name}",
        "seconds": round(seconds, 2),
        "exit": completed.returncode,
    }
    counts = test_counts(output)
    if counts is not None:
        record["tests"] = counts
    facts = gnn_facts(output)
    if facts:
        record["gnn"] = facts
    return record


def host_facts() -> dict[str, str | None]:
    return {
        "system": platform.system(),
        "machine": platform.machine(),
        "julia": run_command([os.environ.get("JULIA_BIN", "julia"), "--version"]),
        "python": platform.python_version(),
        "uv": run_command([shutil.which("uv") or "uv", "--version"]),
    }


def repository_facts() -> dict[str, object]:
    commit = run_command(["git", "rev-parse", "HEAD"])
    dirty = run_command(["git", "status", "--porcelain"])
    return {"commit": commit, "dirty": bool(dirty)}


def build_receipt(arms: list[dict[str, object]], recorded: str) -> dict[str, object]:
    return {
        "schema": SCHEMA,
        "recorded": recorded,
        "host": host_facts(),
        "repository": repository_facts(),
        "arms": arms,
    }


def render(receipt: dict[str, object]) -> str:
    host = receipt["host"]
    repository = receipt["repository"]
    lines = [
        "# Gate measurements",
        "",
        "<!-- generated by scripts/gate_report.py from gate-receipt.json; "
        "refresh with ./run.sh measure, verify with ./run.sh docs -->",
        "",
        f"Recorded {receipt['recorded']} at commit `{str(repository['commit'])[:12]}`,"
        f" measured from the working tree, on {host['system']}/{host['machine']} with"
        f" Julia `{host['julia'] or 'unavailable'}`, Python {host['python']}, uv"
        f" `{host['uv'] or 'unavailable'}`.",
        "",
        "One run per arm, wall time from process start to exit. The arms are",
        "described in [the gate guide](../gate.md).",
        "",
        "| Arm | Command | Wall time | Result | Notes |",
        "| --- | --- | --- | --- | --- |",
    ]
    for arm in receipt["arms"]:
        notes: list[str] = []
        tests = arm.get("tests")
        if tests:
            note = f"{tests['passed']} passed / {tests['total']} total"
            if tests["deferred"]:
                note += f", {tests['deferred']} deferred"
            notes.append(note)
        gnn = arm.get("gnn")
        if gnn:
            notes.append(
                f"gnn {gnn.get('version', 'unknown')} at pinned commit "
                f"{(gnn.get('commit') or 'unknown')[:12]}"
            )
        result = "pass" if arm["exit"] == 0 else f"fail (exit {arm['exit']})"
        lines.append(
            f"| {arm['arm']} | `{arm['command']}` | {arm['seconds']:.2f} s |"
            f" {result} | {'; '.join(notes) or '—'} |"
        )
    lines.append("")
    return "\n".join(lines)


def write_receipt(receipt: dict[str, object]) -> None:
    RECEIPT.parent.mkdir(parents=True, exist_ok=True)
    RECEIPT.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    TABLE.write_text(render(receipt), encoding="utf-8")


def check() -> int:
    if not RECEIPT.is_file() or not TABLE.is_file():
        print(
            "gate: docs/_generated/gate-receipt.json or gate.md is missing; "
            "run ./run.sh measure",
            file=sys.stderr,
        )
        return 1
    receipt = json.loads(RECEIPT.read_text(encoding="utf-8"))
    expected = render(receipt)
    observed = TABLE.read_text(encoding="utf-8")
    if expected != observed:
        print(
            "gate: docs/_generated/gate.md does not match its receipt; "
            "run ./run.sh measure instead of editing it",
            file=sys.stderr,
        )
        return 1
    print("gate: docs/_generated/gate.md matches its receipt")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed table")
    parser.add_argument(
        "--arms",
        default=",".join(ALL_ARMS),
        help=f"comma-separated arms to measure (default: {','.join(ALL_ARMS)})",
    )
    parser.add_argument("--json", action="store_true", help="print the receipt")
    args = parser.parse_args(argv)

    if args.check:
        return check()

    recorded = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    names = [name.strip() for name in args.arms.split(",") if name.strip()]
    unknown = [name for name in names if name not in ALL_ARMS + (LAST_ARM,)]
    if unknown:
        print(f"gate: unknown arm(s) {unknown}", file=sys.stderr)
        return 1

    arms: list[dict[str, object]] = []
    for name in names:
        print(f"gate: measuring {name}", file=sys.stderr)
        arms.append(measure_arm(name))
    receipt = build_receipt(arms, recorded)
    write_receipt(receipt)

    failed = [arm["arm"] for arm in arms if arm["exit"] != 0]
    if failed:
        print(f"gate: arm(s) failed: {failed}; receipt written, doc not committed", file=sys.stderr)
        return 1

    if LAST_ARM not in names:
        print(f"gate: measuring {LAST_ARM}", file=sys.stderr)
        arms.append(measure_arm(LAST_ARM))
        receipt = build_receipt(arms, recorded)
        write_receipt(receipt)
        if arms[-1]["exit"] != 0:
            print(f"gate: arm(s) failed: ['{LAST_ARM}']", file=sys.stderr)
            return 1

    if args.json:
        print(json.dumps(receipt, indent=2, sort_keys=True))
    print(f"gate: wrote {RECEIPT.relative_to(ROOT)} and {TABLE.relative_to(ROOT)}")
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
